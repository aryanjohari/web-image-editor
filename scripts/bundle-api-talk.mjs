/**
 * Bundle api/talk.entry.ts → api/talk.js for Vercel serverless.
 * Pulls in api/_lib + src/talk|packs|recipe|canvas so /var/task needs no ../../src/*.
 */

import * as esbuild from "esbuild";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outfile = path.join(root, "api/talk.js");

await esbuild.build({
  entryPoints: [path.join(root, "api/talk.entry.ts")],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  outfile,
  packages: "bundle",
  banner: {
    js: "// Generated by scripts/bundle-api-talk.mjs — do not edit",
  },
  logLevel: "info",
});

const bundle = readFileSync(outfile, "utf8");
if (bundle.includes("../../src/")) {
  console.error("bundle-api-talk: api/talk.js still contains ../../src/ path literals");
  process.exit(1);
}

console.log("bundle-api-talk: api/talk.js OK");

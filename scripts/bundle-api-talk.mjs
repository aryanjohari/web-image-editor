/**
 * Bundle api/talk.entry.ts → api/talk.js for Vercel serverless.
 * Pulls in api/_lib + src/talk|packs|recipe|canvas so /var/task needs no ../../src/*.
 */

import * as esbuild from "esbuild";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outfile = path.join(root, "api/talk.js");

await esbuild.build({
  entryPoints: [path.join(root, "api/talk.entry.ts")],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  outfile,
  packages: "bundle",
  // Keep Google SDK out of the bundle — its dynamic require() of Node built-ins
  // (e.g. child_process via google-auth-library) breaks in a single ESM file on Vercel.
  external: ["@google/genai"],
  banner: {
    js: "// Generated by scripts/bundle-api-talk.mjs — do not edit",
  },
  logLevel: "info",
});

const bundle = readFileSync(outfile, "utf8");
if (bundle.includes("../../src/")) {
  console.error("bundle-api-talk: api/talk.js still contains ../../src/ path literals");
  process.exit(1);
}
if (!/from\s+["']@google\/genai["']/.test(bundle) && !/import\s*\(\s*["']@google\/genai["']\s*\)/.test(bundle)) {
  console.error("bundle-api-talk: api/talk.js missing external import of @google/genai");
  process.exit(1);
}
if (bundle.includes("google-auth-library") || bundle.includes("Dynamic require of")) {
  console.error("bundle-api-talk: api/talk.js still inlines google-auth-library / dynamic require");
  process.exit(1);
}

console.log("bundle-api-talk: api/talk.js OK (local code bundled; @google/genai external)");
